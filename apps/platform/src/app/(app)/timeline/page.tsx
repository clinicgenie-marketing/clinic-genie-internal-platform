import { listClients, listTimeline } from "@clinic-genie/db";
import { TIMELINE_EVENT_TYPES } from "@clinic-genie/contracts";
import { requireAccess } from "@/lib/session";
import { staffTx } from "@/lib/db";
import { PageHeader, Card } from "@/components/ui/Card";
import { FilterBar, FilterInput, FilterSelect } from "@/components/ui/Filters";
import { TimelineList } from "@/components/modules/TimelineList";
import { label } from "@/components/ui/Badge";
import { Notice } from "@/components/ui/Notice";

export const dynamic = "force-dynamic";
export const metadata = { title: "Timeline" };

export default async function TimelinePage({ searchParams }: { searchParams: Promise<{ client?: string; type?: string; from?: string; to?: string }> }) {
  const access = await requireAccess();
  const { client, type, from, to } = await searchParams;
  const data = await staffTx(access, async (db) => ({
    events: await listTimeline(db, { clientId: client || undefined, eventTypes: type ? [type] : undefined, from: from || undefined, to: to || undefined }),
    clients: await listClients(db),
  }));
  return (
    <>
      <PageHeader title="Change and outcome timeline" description="Material events generated by the workflows: tasks, decisions, SEO and Ads changes, issues, reviews and reporting." />
      <Notice tone="neutral">Later movement in the figures is observed, not proven to be caused by a change. The security audit log is separate, under Admin.</Notice>
      <div className="mt-4">
        <FilterBar>
          <FilterSelect name="client" label="Client" value={client} options={data.clients.map((c) => ({ value: c.id, label: c.name }))} />
          <FilterSelect name="type" label="Event type" value={type} options={TIMELINE_EVENT_TYPES.map((t) => ({ value: t, label: label(t) }))} />
          <FilterInput name="from" label="From" type="date" value={from} />
          <FilterInput name="to" label="To" type="date" value={to} />
        </FilterBar>
      </div>
      <Card><TimelineList events={data.events} /></Card>
    </>
  );
}
