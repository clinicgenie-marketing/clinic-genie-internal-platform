import {
  canEditClient, getGoogleSiteVerification, hasActiveSeoSiteToken, listClients, listSeoBusinessProfiles,
  listSeoPageSettings, listSeoRedirects, listWebsites,
} from "@clinic-genie/db";
import { requireAccess } from "@/lib/session";
import { serviceTx, staffTx } from "@/lib/db";
import { PageHeader, Card, CardHeader } from "@/components/ui/Card";
import { EmptyState, Notice } from "@/components/ui/Notice";
import { SeoSubnav } from "@/components/modules/SeoSubnav";
import { Badge } from "@/components/ui/Badge";
import { clientLabel } from "@/lib/client-label";

export const dynamic = "force-dynamic";
export const metadata = { title: "SEO setup checklist" };

function CheckRow({ title, detail, status }: { title: string; detail: string; status: "ready" | "attention" | "unverified" }) {
  const tone = status === "ready" ? "good" : status === "attention" ? "warn" : "neutral";
  const label = status === "ready" ? "Ready" : status === "attention" ? "Setup needed" : "Not verified here";
  return (
    <li className="flex flex-col gap-1 py-3 sm:flex-row sm:items-start sm:justify-between sm:gap-4">
      <div>
        <div className="text-sm font-medium">{title}</div>
        <p className="text-sm text-muted">{detail}</p>
      </div>
      <Badge tone={tone} className="w-fit shrink-0">{label}</Badge>
    </li>
  );
}

export default async function SeoChecklistPage() {
  const access = await requireAccess();
  const data = await staffTx(access, async (db) => {
    const clients = (await listClients(db)).filter((item) => canEditClient(access, item.id));
    const rows = await Promise.all(clients.map(async (client) => {
      const websites = (await listWebsites(db, client.id)).filter((site) => site.status === "active");
      const profiles = await listSeoBusinessProfiles(db, client.id);
      return Promise.all(websites.map(async (website) => {
        const [pages, redirects, verification, connected] = await Promise.all([
          listSeoPageSettings(db, { websiteId: website.id }),
          listSeoRedirects(db, { websiteId: website.id }),
          getGoogleSiteVerification(db, website.id),
          serviceTx((serviceDb) => hasActiveSeoSiteToken(serviceDb, website.id)),
        ]);
        return { client, website, profiles, pages, redirects, verification, connected };
      }));
    }));
    return rows.flat();
  });

  return (
    <>
      <PageHeader title="SEO setup checklist" description="Readiness indicators based only on saved configuration. This page does not crawl sites or verify Google ownership." />
      <SeoSubnav pathname="/seo/checklist" />
      <Notice tone="neutral">“Ready” means the platform setting exists or the site code supports it; it does not mean Google has crawled, indexed, or approved the website.</Notice>
      {data.length === 0 ? (
        <div className="mt-5"><EmptyState title="No editable active websites">Add an active website to a client before configuring SEO.</EmptyState></div>
      ) : (
        <div className="mt-5 space-y-5">
          {data.map(({ client, website, profiles, pages, redirects, verification, connected }) => {
            const sitePlatform = website.platform.toLowerCase();
            const codeManaged = sitePlatform.includes("next");
            return (
              <Card key={website.id}>
                <CardHeader title={website.name} description={`${clientLabel(client)} · ${website.url ?? "No production URL recorded"} · ${website.platform}`} />
                <ul className="divide-y divide-line px-5 pb-3">
                  <CheckRow
                    title="Published page SEO settings"
                    detail={connected
                      ? pages.length ? `${pages.length} route override(s) saved. The rendered HTML is not crawled by this checklist.` : "No route overrides saved; existing code-defined titles and descriptions may still appear."
                      : "Connect the website with its generated API credential before Genie Works settings can reach it."}
                    status={connected && pages.length > 0 ? "unverified" : "attention"}
                  />
                  <CheckRow
                    title="Individual 301 redirects"
                    detail={connected
                      ? `${redirects.length} active redirect(s) saved. The website deployment must be connected for rules to take effect.`
                      : "The redirect manager is available, but this website has no published-settings credential."}
                    status={connected ? "unverified" : "attention"}
                  />
                  <CheckRow
                    title="XML sitemap"
                    detail={codeManaged
                      ? "Generated by the supported clinic-site code when public indexing is enabled. Live URL and contents are not checked here."
                      : "Sitemap behavior depends on this website platform and has not been inspected."}
                    status={codeManaged ? "unverified" : "attention"}
                  />
                  <CheckRow
                    title="robots.txt"
                    detail={codeManaged
                      ? "Safe generated defaults exist in the supported clinic-site code; preview environments remain disallowed. No live response check was run."
                      : "robots.txt behavior depends on this website platform and has not been inspected."}
                    status={codeManaged ? "unverified" : "attention"}
                  />
                  <CheckRow
                    title="Google Search Console"
                    detail={verification
                      ? "Verification token is saved for publishing. Complete and confirm ownership in Google Search Console."
                      : "No HTML verification token is saved. Domain/DNS verification is not managed here."}
                    status={verification ? "unverified" : "attention"}
                  />
                  {profiles.map((profile) => (
                    <CheckRow
                      key={profile.id}
                      title={`Google Business Profile · ${profile.branch_name}`}
                      detail={profile.setup_status === "staff_marked_verified"
                        ? "Staff marked the setup verified; no Google API or independent ownership check is connected."
                        : profile.setup_status === "in_progress" ? "Setup is recorded as in progress." : "Branch setup has not started."}
                      status={profile.setup_status === "staff_marked_verified" ? "unverified" : "attention"}
                    />
                  ))}
                  {profiles.length === 0 && <CheckRow title="Google Business Profile" detail="No branch reference or setup status is recorded." status="attention" />}
                </ul>
              </Card>
            );
          })}
        </div>
      )}
    </>
  );
}
